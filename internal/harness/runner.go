// Package harness owns the shared model/tool execution loop, context policy and synchronous events.
// 项目协议直接贯穿图节点，保留原始消息、同步事件和取消语义。
package harness

import (
	"context"
	"fmt"

	"github.com/lannokaede/LanAgent/internal/contextbudget"
	"github.com/lannokaede/LanAgent/internal/llm"
	"github.com/lannokaede/LanAgent/internal/tool"
	"github.com/smallnest/langgraphgo/graph"
)

// Runner 可共享；每次运行独立创建图和状态，工具目录在启动后只读。
type Runner struct {
	provider   llm.Provider
	summarizer llm.Provider
	registry   *tool.Registry
	maxRounds  int
	budget     contextbudget.Policy
	format     *llm.ResponseFormat
	pinned     func() string
	tools      ToolPolicy
	recall     func(context.Context, string) (string, error)
}

// WithRecall adds current facts to the request only, never durable run messages.
// Configure before sharing; failures degrade to the original conversation.
func (r *Runner) WithRecall(fn func(context.Context, string) (string, error)) *Runner {
	r.recall = fn
	return r
}

type Event struct {
	Type string
	Data any
}

func NewRunner(provider llm.Provider, registry *tool.Registry, maxRounds int) *Runner {
	return &Runner{provider: provider, registry: registry, maxRounds: maxRounds}
}

// Configure before sharing. Pinned state is generated by trusted workflow code.
func (r *Runner) WithBudget(p contextbudget.Policy) *Runner        { r.budget = p; return r }
func (r *Runner) WithResponseFormat(f *llm.ResponseFormat) *Runner { r.format = f; return r }
func (r *Runner) WithPinnedState(fn func() string) *Runner         { r.pinned = fn; return r }
func (r *Runner) WithToolPolicy(p ToolPolicy) *Runner              { r.tools = p; return r }
func (r *Runner) Run(ctx context.Context, input []llm.Message) ([]llm.Message, *llm.ChatResponse, error) {
	return r.RunWithEvents(ctx, input, nil)
}

// RunWithEvents 的 emit 同步执行。写入失败立即终止，不重放已执行工具。
func (r *Runner) RunWithEvents(
	ctx context.Context,
	input []llm.Message,
	emit func(Event) error,
) ([]llm.Message, *llm.ChatResponse, error) {
	if r.provider == nil || r.registry == nil || r.maxRounds <= 0 {
		return nil, nil, fmt.Errorf("runner is not configured")
	}
	if len(input) == 0 {
		return nil, nil, fmt.Errorf("messages cannot be empty")
	}
	if err := r.tools.validate(); err != nil {
		return nil, nil, err
	}

	if err := llm.ValidateMessages(input); err != nil {
		return nil, nil, err
	}

	// 每次运行创建独立状态，避免不同会话混用消息。
	state := &runState{
		messages: cloneMessages(input),
		emit:     emit,
	}
	return r.runGraph(ctx, state, "model")
}

func (r *Runner) runGraph(ctx context.Context, state *runState, phase string) ([]llm.Message, *llm.ChatResponse, error) {
	if r.provider == nil || r.registry == nil || r.maxRounds <= 0 {
		return nil, nil, fmt.Errorf("runner is not configured")
	}
	if err := r.tools.validate(); err != nil {
		return nil, nil, err
	}
	if phase == "done" && state.final != nil {
		state.final.Usage = state.usage
		return state.messages, state.final, nil
	}
	g := graph.NewStateGraph[*runState]()
	g.AddNode("model", "模型决策", r.plan)
	g.AddNode("tools", "按原始顺序执行工具", r.executeTools)
	g.SetEntryPoint(phase)
	g.AddConditionalEdge("model", func(_ context.Context, s *runState) string {
		if s.final != nil {
			return graph.END
		}
		return "tools"
	})
	g.AddEdge("tools", "model")
	// 不配置节点重试：事件回调或工具可能已经产生副作用。
	app, err := g.Compile()
	if err != nil {
		return state.messages, nil, fmt.Errorf("compile agent graph: %w", err)
	}
	// 保留本次状态指针：框架在普通节点错误时返回零值，调用者仍需完整部分轨迹。
	if _, err := app.Invoke(ctx, state); err != nil {
		return state.messages, nil, fmt.Errorf("agent graph: %w", err)
	}
	if err := ctx.Err(); err != nil {
		return state.messages, nil, err
	}
	if state.final == nil {
		return state.messages, nil,
			fmt.Errorf("agent finished without an answer")
	}

	state.final.Usage = state.usage
	return state.messages, state.final, nil
}

// runState 只在本次串行路径上读写；通过 Checkpoint 保存图边界以供恢复。
type runState struct {
	messages  []llm.Message
	pending   []llm.ToolCall
	final     *llm.ChatResponse
	usage     llm.Usage
	emit      func(Event) error
	round     int
	toolCalls int
	runID     string
	profile   string
	running   string
	save      CheckpointSink
}

func cloneMessages(src []llm.Message) []llm.Message {
	dst := append([]llm.Message(nil), src...)
	for i := range dst {
		dst[i].ToolCalls = append([]llm.ToolCall(nil), src[i].ToolCalls...)
	}
	return dst
}
